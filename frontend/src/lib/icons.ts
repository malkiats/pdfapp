/**
 * Static map from catalog icon names (Lucide, kebab-case) to components.
 * A static map keeps the bundle small (only these icons are shipped) and avoids
 * client-side dynamic icon loading. tests/unit/catalog.test.ts fails if the
 * catalog references an icon that is missing here; unknown names fall back to
 * a generic file icon at runtime.
 */
