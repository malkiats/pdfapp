  Crop,
  Eraser,
  FileCode,
  FileImage,
  FileInput,
  FileMinus,
  FileOutput,
  FileScan,
  FileText,
  FileType,
  GitCompare,
  GitCompareArrows,
  Image,
  Languages,
  LayoutGrid,
  ListChecks,
  ListOrdered,
  Lock,
  LockOpen,
  MessageCircleQuestion,
  Minimize2,
  Monitor,
  Newspaper,
  PenLine,
  Pencil,
